"""Diff of the development tree for a new prior0 table

    prior0_diff.py <tree (content of the compressor source dir)> <endbau.sh>
                   <z3-prior0.float16> <SET> <work dir> <description>

The coder must use the same prior0 vector as the training (the replacement
prior of every row without a stream target).  This tool turns the
`z3-prior0.float16` of a training package into a change of the development
tree of the compressor, which is not part of this package:
 - a new header `src/tf1/tf1_prior0_set_v<SET>.h` (208 float16 bit patterns),
 - the selector in `src/neif_tf1.h` and `src/tf1/tf1_prior0.h` extended by
   `== SET` (both files, otherwise a build would silently fall back),
 - the form guards `... != 7` turned into `< 7` (a SET above 7 is also a new
   form),
 - the build script `scripts/endbau.sh` learns the sha256 of the new table.
Writes <work dir>/prior0_set_v<SET>.diff (git format a/ b/, paths relative to
the repository).  The strings it writes and the anchors it looks for are those
of the development tree, so they keep its names and its German comment text.
`<description>` only enters comment lines.
"""
import sys, os, shutil, hashlib, subprocess, re
import numpy as np

baum, endbau, p0f, SET, wd, text = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4]), sys.argv[5], sys.argv[6]
raw = open(p0f, "rb").read(); assert len(raw) == 416
sha = hashlib.sha256(raw).hexdigest()
w = np.frombuffer(raw, dtype=np.uint16)
a = os.path.join(wd, "a"); b = os.path.join(wd, "b")
shutil.rmtree(wd, ignore_errors=True)
for r in (a, b):
    os.makedirs(os.path.join(r, "scripts"))
    shutil.copytree(baum, os.path.join(r, "src/cmix-neifv9"))
    shutil.copy(endbau, os.path.join(r, "scripts/endbau.sh"))
S = os.path.join(b, "src/cmix-neifv9/src")
zeilen = []
for i in range(0, 208, 8):
    zeilen.append("  " + ", ".join("0x%04x" % int(v) for v in w[i:i+8]) + ("," if i + 8 < 208 else ""))
kopf = f"""// tf1_prior0_set_v{SET}.h - generated by prior0_diff.py from z3-prior0.float16, DO NOT EDIT BY HAND.
// {text}
// Selected with NEIF_TF1_PRIOR0_SET={SET} (src/neif_tf1.h and src/tf1/tf1_prior0.h).
// Order-0 byte distribution of the training package, 208 float16 values as raw
// bit patterns in the order of the frozen byte set.
// sha256: {sha}
#ifndef NEIF_TF1_PRIOR0_SET_V{SET}_H
#define NEIF_TF1_PRIOR0_SET_V{SET}_H

#define NEIF_TF1_PRIOR0_LEN 208
#define NEIF_TF1_PRIOR0_SHA256 "{sha}"
#define NEIF_TF1_PRIOR0_INIT {{ \\
""" + " \\\n".join(zeilen) + f""" \\
}}

#endif  // NEIF_TF1_PRIOR0_SET_V{SET}_H
"""
open(os.path.join(S, f"tf1/tf1_prior0_set_v{SET}.h"), "w").write(kopf)
for datei, inc in (("neif_tf1.h", f"tf1/tf1_prior0_set_v{SET}.h"), ("tf1/tf1_prior0.h", f"tf1_prior0_set_v{SET}.h")):
    p = os.path.join(S, datei); s = open(p).read()
    alt = "#if NEIF_TF1_PRIOR0_SET == 7\n"
    assert s.count(alt) == 1, (datei, s.count(alt))
    s = s.replace(alt, f"#if NEIF_TF1_PRIOR0_SET == {SET}\n#include \"{inc}\"\n#elif NEIF_TF1_PRIOR0_SET == 7\n")
    s, n = re.subn(r"\(gebaut sind 4, 5 und 7\)", f"(gebaut sind 4, 5, 7 und {SET})", s)
    assert n == 1, (datei, n)
    if datei == "neif_tf1.h":
        s, n = re.subn(r"&& NEIF_TF1_PRIOR0_SET != 7 && !NEIF_TF1_FORMBRUCH_OK", "&& NEIF_TF1_PRIOR0_SET < 7 && !NEIF_TF1_FORMBRUCH_OK", s)
        assert n >= 4, n
        print("form guards != 7 -> < 7:", n)
    open(p, "w").write(s)
e = os.path.join(b, "scripts/endbau.sh"); s = open(e).read()
anker = "PRIOR0_V7=b7e803299079ff9fb1d915b478959eaa0eba059a2c9f4fe00d5ee5bfbc1ea49e\n"
assert s.count(anker) == 1
s = s.replace(anker, anker + f"PRIOR0_V{SET}={sha}   # {text}\n")
ca = '  "$PRIOR0_V7")  PKG=v7; SOLL_ALIAS=1; SOLL_PRIOR0=7 ;;\n'
assert s.count(ca) == 1
s = s.replace(ca, ca + f'  "$PRIOR0_V{SET}")  PKG=v{SET}; SOLL_ALIAS=1; SOLL_PRIOR0={SET} ;;\n')
open(e, "w").write(s)
out = os.path.join(wd, f"prior0_set_v{SET}.diff")
r = subprocess.run(["diff", "-ruN", "a", "b"], cwd=wd, capture_output=True, text=True)
assert r.returncode == 1, r.stderr
t = r.stdout.replace("--- a/", "--- a/").replace("diff -ruN a/", "diff -ruN a/")
open(out, "w").write(t)
print("prior0", sha, "SET", SET, "diff", out, hashlib.sha256(t.encode()).hexdigest()[:16], len(t.splitlines()), "lines")
